pub struct AreaDef {
    /// 実在の街の名前（駅名）
    pub name: &'static str,
    /// 読みがな
    pub kana: &'static str,
    pub address: &'static str,
    pub description: &'static str,
    /// 最寄りの路線
    pub lines: &'static str,
    /// 駅の緯度・経度（タウンマップの位置）
    pub lat: f64,
    pub lon: f64,
    /// 市場規模（入塾希望者数の倍率）
    pub pool: f64,
    /// 週あたりの家賃
    pub rent: i64,
    /// 開校費（敷金・内装・備品）
    pub open_cost: i64,
    /// 教室の物件を買い取る場合の価格
    pub property_price: i64,
    /// 市場規模の年間の伸び（新興エリアは伸び、高齢化エリアは縮む）
    pub pool_growth: f64,
    /// 地方（画面のまとまり）
    pub region: &'static str,
    /// 出店できるようになる条件
    pub unlock: AreaUnlock,
}

